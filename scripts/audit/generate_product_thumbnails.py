#!/usr/bin/env python3
"""Generate smaller, separate WebP derivatives for catalogue-card images.

Original product files are never changed, enlarged, padded, or rewritten.
Only the first image used by catalogue cards is derived, with a 400 px edge
limit so high-density mobile cards can use an appropriately sized resource.
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
CATALOGUE = ROOT / "assets/data/catalogue-index.json"
SOURCE_ROOT = ROOT / "assets/images/products"
THUMB_ROOT = ROOT / "assets/images/product-thumbnails"
MAX_EDGE = 400
QUALITY = 78


def clean(value) -> str:
    return str(value or "").strip()


def first_filename(product: dict) -> str:
    gallery = product.get("gallery") or []
    filename = ""
    if isinstance(gallery, list) and gallery:
        first = gallery[0]
        if isinstance(first, dict):
            filename = clean(first.get("filename") or first.get("file") or first.get("name"))
        else:
            filename = clean(first)
    if not filename:
        raw = clean(product.get("image") or product.get("primary_image"))
        filename = raw.rsplit("/", 1)[-1] if raw else ""
    return Path(filename).name if filename else ""


def generate() -> tuple[int, int, int, int]:
    if not CATALOGUE.is_file():
        raise SystemExit(f"Missing catalogue index: {CATALOGUE.relative_to(ROOT)}")
    products = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    if not isinstance(products, list):
        raise SystemExit("Catalogue index must contain a JSON array")

    inspected = generated = skipped = saved_bytes = 0
    expected_targets: set[Path] = set()

    for product in products:
        if not isinstance(product, dict) or product.get("active") is False:
            continue
        folder = clean(product.get("image_folder") or product.get("id"))
        filename = first_filename(product)
        if not folder or Path(folder).name != folder or not filename:
            skipped += 1
            continue

        source = SOURCE_ROOT / folder / filename
        if not source.is_file():
            skipped += 1
            continue
        inspected += 1

        target = THUMB_ROOT / folder / f"{Path(filename).stem}.webp"
        try:
            with Image.open(source) as original:
                oriented = ImageOps.exif_transpose(original)
                width, height = oriented.size
                if max(width, height) <= MAX_EDGE:
                    target.unlink(missing_ok=True)
                    continue

                image = oriented.convert(
                    "RGBA" if ("A" in oriented.getbands() or "transparency" in oriented.info) else "RGB"
                )
                image.thumbnail((MAX_EDGE, MAX_EDGE), Image.Resampling.LANCZOS)
                target.parent.mkdir(parents=True, exist_ok=True)
                image.save(target, "WEBP", quality=QUALITY, method=6, exact=True)

            if target.stat().st_size >= source.stat().st_size * 0.98:
                target.unlink(missing_ok=True)
                continue

            expected_targets.add(target)
            saved_bytes += source.stat().st_size - target.stat().st_size
            generated += 1
        except (OSError, ValueError) as exc:
            target.unlink(missing_ok=True)
            raise SystemExit(f"Could not create card thumbnail for {source.relative_to(ROOT)}: {exc}") from exc

    # This directory is exclusively generated by this script. Remove stale
    # thumbnails for products no longer selected by the active catalogue.
    if THUMB_ROOT.exists():
        for stale in THUMB_ROOT.rglob("*"):
            if stale.is_file() and stale not in expected_targets:
                stale.unlink()
        for directory in sorted((p for p in THUMB_ROOT.rglob("*") if p.is_dir()), reverse=True):
            try:
                directory.rmdir()
            except OSError:
                pass

    return inspected, generated, skipped, saved_bytes


if __name__ == "__main__":
    inspected, generated, skipped, saved_bytes = generate()
    print(
        "[IMAGE] Product-card derivatives: "
        f"{generated} thumbnails from {inspected} active primary images; "
        f"{saved_bytes:,} bytes saved across derivatives; {skipped} missing/invalid primary images. "
        "Native product images remain unchanged."
    )
